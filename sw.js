const CACHE_NAME = 'breathe-bloom-ios-v1';
const APP_FILES = [
  './',
  './index.html',
  './manifest.webmanifest',
  './assets/icon-192.png',
  './assets/icon-512.png',
  './assets/apple-touch-icon.png',
  './assets/photos/cat-cow.jpg',
  './assets/photos/bridge.jpg',
  './assets/photos/seated-breathing.jpg',
  './assets/photos/cobra.jpg',
  './assets/photos/mountain.jpg',
  './assets/photos/warrior-1.jpg',
  './assets/photos/warrior-2.jpg',
  './assets/photos/triangle.jpg',
  './assets/photos/downward-dog.jpg',
  './assets/photos/childs-pose.jpg',
  './assets/photos/tree.jpg'
];

self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then(cache => cache.addAll(APP_FILES))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(key => key.startsWith('breathe-bloom-') && key !== CACHE_NAME).map(key => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET' || new URL(event.request.url).origin !== self.location.origin) return;
  event.respondWith(
    caches.match(event.request).then(cached => cached || fetch(event.request).then(response => {
      if (response && response.ok) {
        const copy = response.clone();
        caches.open(CACHE_NAME).then(cache => cache.put(event.request, copy));
      }
      return response;
    }))
  );
});
